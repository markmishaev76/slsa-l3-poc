#!/bin/bash
# Compare SLSA L2 vs L3 workflow structures
# This demonstrates WHY reusable workflows matter for L3

echo "═══════════════════════════════════════════════════════════════"
echo "  SLSA Level 2 vs Level 3: The Key Difference"
echo "═══════════════════════════════════════════════════════════════"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│                    SLSA BUILD LEVEL 2                           │"
echo "│              (Single workflow - NO isolation)                   │"
echo "├─────────────────────────────────────────────────────────────────┤"
echo "│                                                                 │"
echo "│   .github/workflows/build.yml                                   │"
echo "│   ┌─────────────────────────────────────────────────────────┐  │"
echo "│   │  jobs:                                                   │  │"
echo "│   │    build:                                                │  │"
echo "│   │      steps:                                              │  │"
echo "│   │        - name: Build              ◄── Can be modified   │  │"
echo "│   │        - name: Attest             ◄── Can be modified   │  │"
echo "│   └─────────────────────────────────────────────────────────┘  │"
echo "│                                                                 │"
echo "│   ⚠️  Problem: A malicious actor with write access can         │"
echo "│      modify BOTH the build AND attestation steps               │"
echo "│                                                                 │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""

echo "┌─────────────────────────────────────────────────────────────────┐"
echo "│                    SLSA BUILD LEVEL 3                           │"
echo "│              (Reusable workflow - ISOLATED)                     │"
echo "├─────────────────────────────────────────────────────────────────┤"
echo "│                                                                 │"
echo "│   .github/workflows/ci.yml (CALLER)                            │"
echo "│   ┌─────────────────────────────────────────────────────────┐  │"
echo "│   │  jobs:                                                   │  │"
echo "│   │    build:                                                │  │"
echo "│   │      uses: ./.github/workflows/build-service.yml        │  │"
echo "│   │      with:                                               │  │"
echo "│   │        image_name: my-app     ◄── Can only pass inputs  │  │"
echo "│   └─────────────────────────────────────────────────────────┘  │"
echo "│                         │                                       │"
echo "│                         ▼                                       │"
echo "│   .github/workflows/build-service.yml (REUSABLE)               │"
echo "│   ┌─────────────────────────────────────────────────────────┐  │"
echo "│   │  on: workflow_call                                       │  │"
echo "│   │  jobs:                                                   │  │"
echo "│   │    build:                                                │  │"
echo "│   │      steps:                                              │  │"
echo "│   │        - name: Build              ◄── CANNOT be changed │  │"
echo "│   │        - name: Attest             ◄── CANNOT be changed │  │"
echo "│   └─────────────────────────────────────────────────────────┘  │"
echo "│                                                                 │"
echo "│   ✅ Benefit: Caller cannot modify build/attestation logic     │"
echo "│      The reusable workflow is the \"trusted build service\"     │"
echo "│                                                                 │"
echo "└─────────────────────────────────────────────────────────────────┘"
echo ""

echo "═══════════════════════════════════════════════════════════════"
echo "  SLSA L3 Verification"
echo "═══════════════════════════════════════════════════════════════"
echo ""
echo "To verify SLSA L3, you MUST specify the signer workflow:"
echo ""
echo "  # L2 verification (just checks signature exists)"
echo "  gh attestation verify oci://IMAGE --owner OWNER"
echo ""
echo "  # L3 verification (checks it came from specific workflow)"
echo "  gh attestation verify oci://IMAGE --owner OWNER \\"
echo "      --signer-workflow OWNER/REPO/.github/workflows/build-service.yml"
echo ""
echo "The --signer-workflow flag proves the artifact was built by"
echo "the ISOLATED reusable workflow, not a modified caller workflow."
echo ""
